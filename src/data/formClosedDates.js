// 更新希望日カレンダーで「選択不可」にする休業日（夏季休業・年末年始など）。
// 土日・祝日は自動で選択不可になるため、ここには「平日だが休業」の日だけを登録すればOK。
//
// 編集方法：
//   - 期間で指定 … { from: '開始日', to: '終了日' }（両端を含む）
//   - 1日だけ指定 … { from: '日付', to: '日付' }（from と to を同じ日付に）
//   - 日付は 'YYYY-MM-DD' 形式（例: '2026-08-13'）
//   - 毎年更新が必要です（年が変わったら新しい年の期間を追記してください）

export const CLOSED_RANGES = [
  // 夏季休業（例）：実際の休業日に書き換えてください
  { from: '2026-08-12', to: '2026-08-14' },

  // 年末年始（例）：実際の休業日に書き換えてください
  { from: '2026-12-28', to: '2027-01-04' },
]

// dayjs オブジェクトが休業日に該当するか判定
export const isClosedDate = (d) => {
  const s = d.format('YYYY-MM-DD')
  return CLOSED_RANGES.some((r) => s >= r.from && s <= r.to)
}
